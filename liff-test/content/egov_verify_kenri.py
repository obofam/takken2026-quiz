# 条文だけでは結論が出ず、判例・通説の確認が要るもの（今回は該当なし）
NEEDS_REVIEW = {}


def text_of(node, out):
    if isinstance(node, str):
        out.append(node)
    elif isinstance(node, dict):
        if node.get("tag") == "Rt":
            return
        for c in node.get("children", []):
            text_of(c, out)
    elif isinstance(node, list):
        for c in node:
            text_of(c, out)


_cache = {}


def article(law, art):
    key = (law, art)
    if key not in _cache:
        url = (f"https://laws.e-gov.go.jp/api/2/law_data/{law}"
               f"?elm=MainProvision-Article_{art}&asof={ASOF}&response_format=json")
        with urllib.request.urlopen(url, timeout=60) as r:
            d = json.loads(r.read().decode("utf-8"))
        out = []
        text_of(d.get("law_full_text"), out)
        _cache[key] = (re.sub(r"\s+", "", "".join(out)), d["revision_info"]["law_revision_id"])
    return _cache[key]


def main():
    ok = ng = 0
    for qid, specs in CHECKS:
        problems, notes = [], []
        for law, art, must, absent in specs:
            try:
                t, rev = article(law, art)
            except Exception as e:  # 取得失敗は NG 扱い
                problems.append(f"{law} 第{art}条 取得失敗: {e}")
                continue
            notes.append(f"{rev} 第{art.replace('_', 'の')}条")
            for k in must:
                if k not in t:
                    problems.append(f"第{art}条に「{k}」が無い")
            for k in absent:
                if k in t:
                    problems.append(f"第{art}条に「{k}」がある")
        if problems:
            status = "NG"; ng += 1
        elif qid in NEEDS_REVIEW:
            status = "要確認"
        else:
            status = "条文照合OK"; ok += 1
        print(f"{qid}\t{status}\t{' / '.join(notes)}")
        for p in problems:
            print("   !", p)
        if qid in NEEDS_REVIEW:
            print("   -", NEEDS_REVIEW[qid])
    print(f"\n照合OK {ok} / 要確認 {len(NEEDS_REVIEW)} / NG {ng}（基準日 {ASOF}）")
    return 1 if ng else 0


if __name__ == "__main__":
    sys.exit(main())
